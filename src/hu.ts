export function allCopy(): string[] {
  const out: string[] = [];
  const walk = (value: unknown): void => {
    if (typeof value === "string") out.push(value);
    else if (Array.isArray(value)) value.forEach(walk);
    else if (value && typeof value === "object") Object.values(value as object).forEach(walk);
  };
  walk(hu);
  walk(levelName);
  walk(levelBlurb);
  out.push(
    hu.levelUp("A2"),
    hu.placement.progress(3, 10),
    hu.home.dueLine(0),
    hu.home.dueLine(1),
    hu.home.dueLine(12),
    hu.home.learnedLine(0),
    hu.home.learnedLine(8),
    hu.home.newLine(1, 8),
    hu.home.freshLine(0),
    hu.home.freshLine(4),
    hu.cards.queue(1),
    hu.cards.queue(6),
    hu.practice.accent("az alma"),
    hu.practice.wrong("a kutya"),
    hu.practice.score(3),
    hu.practice.choice(2),
    hu.gen.image(1, 3),
    hu.gen.audio(2, 3),
    hu.gen.done(1),
    hu.gen.done(3),
  );
  return out;
}
